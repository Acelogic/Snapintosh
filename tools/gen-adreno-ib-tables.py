"""Generate compat/adreno-ib-tables.h: the CP_PROTECT ranges the kext's IB validator removes from the register
allowlist (design 3.3: allowed = KNOWN - PROTECTED).

Source of truth is q1n1 (never typed by hand here):
  tools/adreno_x2.py  X285_PROTECT      the 52 x285_protect_regs words hw_init writes to CP_PROTECT_GLOBAL[0..51]
                      CP_PROTECT_CNTL   (bit 1 LAST_SPAN_INF: the last range extends to the end of the register space)
  tools/a8xx_regs.py  REGS              the 284 IB registers; their expansion is q1n1's KNOWN_OFFSETS
  tools/test-a16gpu-p6p7.py             the model that enforces exactly this rule on the hardware-proven streams:
                                        PROTECTED = [(reg, reg + ((word >> 18) & 0x1fff))], inclusive
KNOWN itself comes from gpu/adreno-kext/include/AdrenoA8xxRegs.h (a8xx_ib_regs, generated from Mesa's XML); this
header only pins its expanded size so the C side can prove both generators still agree.

  python3 tools/gen-adreno-ib-tables.py [--q1n1 ../q1n1/tools] [--out compat/adreno-ib-tables.h] [--check]
"""
from pathlib import Path
import argparse
import hashlib
import importlib.util
import sys

ROOT = Path(__file__).resolve().parents[1]
GPL_NOTICE = [
    '/*',
    ' * adreno_ib_protect[] is the x285_protect_regs table of Linux',
    ' * drivers/gpu/drm/msm/adreno/a6xx_catalog.c, translated by q1n1 tools/adreno_x2.py,',
    ' * so this file is GPL-2.0-only (LICENSES/GPL-2.0-only.txt):',
    ' *   Copyright (C) 2013-2014 Red Hat',
    ' *   Author: Rob Clark <robdclark@gmail.com>',
    ' *   Copyright (c) 2014,2017 The Linux Foundation. All rights reserved.',
    ' * A monitor binary built with this table is a combined work, distributable under',
    ' * GPL-2.0 (see LICENSE and THIRD_PARTY_NOTICES.md).',
    ' */',
]


def load(path, name):
    spec = importlib.util.spec_from_file_location(name, path)
    module = importlib.util.module_from_spec(spec)
    sys.modules[name] = module          # dataclasses resolve their module through sys.modules
    spec.loader.exec_module(module)
    return module


def render(q1n1, mesa):
    sys.path.insert(0, str(q1n1))
    R = load(q1n1 / 'adreno_x2.py', 'adreno_x2')
    X = load(q1n1 / 'a8xx_regs.py', 'a8xx_regs')
    words = list(R.X285_PROTECT)
    assert len(words) == 52, len(words)
    known = set()
    for _name, (offset, bits, _fields, stride, count) in X.REGS.items():
        for i in range(count):
            for half in range(2 if bits == 64 else 1):
                known.add(offset + i * stride + half)
    draw_known = len(known)
    G = load(ROOT / 'tools' / 'gen-a8xx-regs.py', 'a8xx_contract_gen')
    assert set(G.DRAW_REG_NAMES) == set(X.REGS), 'draw register baseline changed'
    M = G.Mesa(str(mesa))
    assert M.revision() == 'bbeb2dca9feed6ac88d71234a9dc5ae8aeed4275', 'unqualified Mesa revision'
    regs = G.regs_of(M, M.load('a6xx.xml'), domains=G.CORE_DOMAINS)
    compute_known = set()
    for name in G.CS_REG_NAMES:
        r = regs[name]
        compute_known.update(r['offset'] + i * r['stride'] + half
                             for i in range(r['length']) for half in range(2 if r['bits'] == 64 else 1))
    assert not known & compute_known, 'compute register offsets overlap draw'
    known |= compute_known
    ranges = [(w & 0x3FFFF, (w & 0x3FFFF) + ((w >> 18) & 0x1FFF)) for w in words]
    for w in words:
        assert (w >> 18) & 0x1FFF == ((w >> 18) & 0x3FFF) & 0x1FFF
    last_span_inf = bool(R.CP_PROTECT_CNTL & 2)
    protected_known = sorted(o for o in known if any(lo <= o <= hi for lo, hi in ranges) or
                             (last_span_inf and o >= ranges[-1][0]))
    digest = {name: hashlib.sha256((q1n1 / name).read_bytes()).hexdigest()
              for name in ('adreno_x2.py', 'adreno_x2_protect.py', 'a8xx_regs.py', 'test-a16gpu-p6p7.py')
              if (q1n1 / name).exists()}
    lines = [
        '/* SPDX-License-Identifier: GPL-2.0-only */', *GPL_NOTICE,
        '/*',
        ' * adreno-ib-tables.h - GENERATED by tools/gen-adreno-ib-tables.py. Do not edit; regenerate with',
        ' *   python3 tools/gen-adreno-ib-tables.py',
        ' * from q1n1 (sha256):',
        *[f' *   tools/{name} {h}' for name, h in digest.items()],
        ' * CP_PROTECT_GLOBAL[0..51] as q1n1 hw_init writes them (adreno_x2.X285_PROTECT, a6xx_catalog.c x285_protect_regs):',
        ' * word = register (bits 0..17) | count (bits 18..30) | NORDWR (bit 31); the range is [register, register + count],',
        ' * inclusive, the rule tools/test-a16gpu-p6p7.py enforces on the hardware-proven streams. CP_PROTECT_CNTL sets',
        ' * LAST_SPAN_INF, so the last range extends to the end of the register space (the validator applies it too).',
        f' * q1n1 a8xx_regs.REGS: {draw_known} draw offsets; explicit gen-a8xx-regs.CS_REG_NAMES:',
        f' * {len(compute_known)} additional offsets from Mesa {M.revision()}.',
        f' * a6xx.xml sha256 {M.xml_sha("a6xx.xml")}',
        f' * Combined: {len(known)} KNOWN dword offsets (max {max(known):#x}); '
        f'{len(protected_known)} of them are protected.',
        ' */',
        '#ifndef ADRENO_IB_TABLES_H',
        '#define ADRENO_IB_TABLES_H',
        '#include <stdint.h>',
        '',
        f'#define ADRENO_IB_PROTECT_COUNT {len(words)}u',
        f'#define ADRENO_IB_PROTECT_CNTL {R.CP_PROTECT_CNTL:#010x}u',
        f'#define ADRENO_IB_PROTECT_LAST_SPAN_INF {1 if last_span_inf else 0}u',
        '#define ADRENO_IB_PROTECT_REG(w) ((w) & 0x3ffffu)',
        '#define ADRENO_IB_PROTECT_LEN(w) (((w) >> 18) & 0x1fffu)',
        f'#define ADRENO_IB_KNOWN_DRAW_OFFSETS {draw_known}u',
        f'#define ADRENO_IB_KNOWN_CS_OFFSETS {len(compute_known)}u',
        f'#define ADRENO_IB_KNOWN_OFFSETS {len(known)}u        /* exact draw baseline plus explicit CS extension */',
        f'#define ADRENO_IB_KNOWN_PROTECTED {len(protected_known)}u      /* KNOWN offsets inside a protected range */',
        f'static const uint32_t adreno_ib_protect[ADRENO_IB_PROTECT_COUNT] = {{',
    ]
    for i in range(0, len(words), 6):
        lines.append('    ' + ' '.join(f'{w:#010x}u,' for w in words[i:i + 6]))
    lines += ['};', '', '#endif /* ADRENO_IB_TABLES_H */', '']
    return '\n'.join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--q1n1', type=Path, default=ROOT.parent / 'q1n1' / 'tools')
    ap.add_argument('--out', type=Path, default=ROOT / 'compat' / 'adreno-ib-tables.h')
    ap.add_argument('--mesa', type=Path, default=ROOT / 'gpu' / 'air2ir3' / 'third_party' / 'mesa')
    ap.add_argument('--check', action='store_true', help='fail unless --out already has exactly this content')
    args = ap.parse_args()
    text = render(args.q1n1.resolve(), args.mesa.resolve())
    if args.check:
        current = args.out.read_text() if args.out.exists() else None
        if current != text:
            raise SystemExit(f'{args.out} is stale: regenerate with tools/gen-adreno-ib-tables.py')
        print(f'fresh: {args.out}')
        return
    args.out.write_text(text)
    print(f'wrote {args.out}')


if __name__ == '__main__':
    main()
