#!/bin/zsh
# SPDX-License-Identifier: MIT
# cleanroom.sh - verifier must-fix 9: rebuild everything from a clean copy of this tree, following
# README.md "Rebuild from scratch" literally, and check the result against this tree.
#
#   tools/cleanroom.sh [dest]        (default: scratch/cleanroom; takes ~4 min on the M3 Max)
#   MESA_URL=<mirror> tools/cleanroom.sh   (default: this tree's third_party/mesa as a local git mirror;
#                                           the pinned revision is fetched from it, patches applied fresh)
# The copy contains only what a checkout contains: src/ tools/ tests/ patches/ vtools/ xrscenes/ and the docs.
# No build/, cache/, results/, scenes/, scratch/, corpus/, third_party/: every one of those is
# regenerated by the documented commands.  Writes results/cleanroom.json in THIS tree.
set -e
ROOT=${0:a:h:h}
DEST=${1:-$ROOT/scratch/cleanroom}
export MESA_URL=${MESA_URL:-$ROOT/third_party/mesa}
T0=$(date +%s)
rm -rf $DEST; mkdir -p $DEST
for d in src tools tests patches vtools xrscenes; do rsync -a --exclude __pycache__ --exclude '*.o' $ROOT/$d $DEST/; done
cp $ROOT/*.md $DEST/ 2>/dev/null || true
cd $DEST
# verify2 item 8: sources only.  Any compiled binary in the copy fails the run (the Metal tools are
# built from source by src/build.sh all, below).
BIN=$(find . -type f -perm +111 -exec file {} + | grep -E 'Mach-O|ELF' | cut -d: -f1 || true)
[[ -z "$BIN" ]] || { echo "prebuilt binaries in the checkout: $BIN"; exit 1; }
log() { echo "== $*"; }
log mesa-setup;   zsh tools/mesa-setup.sh > mesa-setup.log 2>&1
log mesa-ninja;   zsh tools/mesa-ninja.sh > mesa-ninja.log 2>&1
log build;        zsh src/build.sh all > build.log 2>&1; zsh src/build.sh v0 >> build.log 2>&1
log corpus;       python3 tools/corpus.py > corpus.log
log templates;    python3 tools/templates.py > templates.log
log scenes;       python3 tools/scenes.py > scenes.log
log regress;      python3 tests/regress.py > regress.log 2>&1 || true
log sweep;        python3 tools/sweep.py --out results/fixed --cache cache --groups skylight_base,coredisplay,qc_pipelines,templates,xr_targets > sweep.log 2>&1
log exec;         python3 tools/exec.py sl_simple_texture cd_texture_copy xr554_tint_premul_over > exec.log 2>&1 || true
log reflcmp;      python3 vtools/reflcmp.py 200 > reflcmp.log 2>&1 || true
# verify3 item 5 / verify4 item 5: the round-to-round diff tools need earlier rounds' results/, which a
# checkout does not have; each must say SKIP instead of printing nothing.
log diffs;        { python3 tools/unsetdiff.py; python3 tools/fix2diff.py; python3 tools/rounddiff.py results/fix2 'fix round 2'; } > diffs.log 2>&1 || true
python3 - "$ROOT" "$DEST" "$(( $(date +%s) - T0 ))" <<'PY'
import json, os, re, sys, time
root, dest, secs = sys.argv[1], sys.argv[2], int(sys.argv[3])
def rows(d, g): return {json.loads(l)['id']: json.loads(l) for l in open(os.path.join(d, 'results', 'fixed', g + '.jsonl'))}
same = diff = 0; missing = []
for g in ('skylight_base', 'coredisplay', 'qc_pipelines', 'templates', 'xr_targets'):
    a, b = rows(root, g), rows(dest, g)
    for k, r in b.items():
        if k not in a: missing.append(k); continue
        if (r.get('cache_key'), r.get('blob_sha256')) == (a[k].get('cache_key'), a[k].get('blob_sha256')): same += 1
        else: diff += 1
reg = open(os.path.join(dest, 'regress.log')).read()
m = re.search(r'(\d+)/(\d+) passed(, (\d+) skipped)?', reg)
cid_a = open(os.path.join(root, 'cache', 'manifest.json')).read(); cid_b = open(os.path.join(dest, 'cache', 'manifest.json')).read()
cid_same = json.loads(cid_a)['compiler_id'] == json.loads(cid_b)['compiler_id']
ex = open(os.path.join(dest, 'exec.log')).read()
exec_ok = ex.count('PASS') >= 3 and 'FAIL' not in ex
rl = open(os.path.join(dest, 'reflcmp.log')).read()
refl_ok = os.path.exists(os.path.join(dest, 'build', 'mtlrefl')) and 'Traceback' not in rl and "'match'" in rl
dl = open(os.path.join(dest, 'diffs.log')).read().splitlines()
skip_ok = len(dl) == 3 and all(l.startswith('SKIP:') for l in dl)
ok = diff == 0 and not missing and m and int(m.group(1)) + int(m.group(4) or 0) == int(m.group(2)) and cid_same and exec_ok and refl_ok and skip_ok
res = dict(ok=bool(ok), date=time.strftime('%Y-%m-%d %H:%M'), seconds=secs, dest=os.path.relpath(dest, root),
           identical_key_blob=same, different=diff, missing=missing[:5], regress=m.group(0) if m else None,
           compiler_id_identical=cid_same, exec_ok=exec_ok, diff_tools_skip=skip_ok, mtlrefl_built_from_source=refl_ok, reflcmp=([l for l in rl.splitlines() if "'match'" in l] or [''])[0][:160],
           summary=f"{same} (key, blob) identical, {diff} different; regress {m.group(0) if m else '?'}; compiler_id identical: {cid_same}; exec ok: {exec_ok}; mtlrefl from source + reflcmp: {refl_ok}; unsetdiff/fix2diff/rounddiff SKIP: {skip_ok}; {secs} s")
json.dump(res, open(os.path.join(root, 'results', 'cleanroom.json'), 'w'), indent=1)
print(json.dumps(res, indent=1))
sys.exit(0 if ok else 1)
PY
