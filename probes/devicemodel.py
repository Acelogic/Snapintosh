def pmgr_cpu_boot_policy(dt):
    """Bind zero software votes to the actual single-CPU guest handoff.

    cpu0 executes; the other five declared CPUs have never been released.
    Both cluster-control interfaces remain held active. Power/launch changes
    need a future CPU lifecycle backend, rather than fixed-active PS requests.
    """
    prefix='/device-tree/cpus/'
    nodes={path for path in dt.nodes if path.startswith(prefix) and path.count('/')==3}
    if nodes!={prefix+f'cpu{i}' for i in range(6)}:
        raise ValueError('CPU power boot policy requires the audited six-node topology')
    for cpu in range(6):
        cluster=int(cpu>=4);node=prefix+f'cpu{cpu}'
        expected={'cpu-id':struct.pack('<I',cpu),'cluster-id':struct.pack('<I',cluster),
                  'reg':struct.pack('<I',cpu if cpu<4 else 0x100+cpu-4),
                  'cluster-type':b'P\0' if cluster else b'E\0',
                  'state':b'waiting\0' if cpu else b'running\0'}
        for key,value in expected.items():
            prop=dt.nodes[node].get(key)
            if prop is None or prop.placeholder or prop.value!=value:
                raise ValueError(f'{node}: CPU power boot policy differs at {key}')
    return PMGR_CPU0_BOOT_V1


