def _dart_boot_policy(dt, device):
    policies={
        '/device-tree/arm-io/dart-sio': ('SIO',DART_SIO_BOOT_V1,16,((0x385060000,0x20000),),
            'bf2fe3cc29c084894652917ba2ffabdc327905ffecde809a00d3922aa5309bec'),
        '/device-tree/arm-io/dart-sep': ('SEP',DART_SEP_BOOT_V1,3,((0x280b80000,0x20000),),
            '2fbea55ebfea208ee215a03d81f2097066381b1f73bb4d29003cf169e88fa922'),
        '/device-tree/arm-io/dart-ane': ('ANE',DART_ANE_INIT_V1,16,
            ((0x401800000,0xc000),(0x401820000,0x20000),
             (0x401840000,0x20000),(0x401810000,0x4000)),
            '864851bde49d3eda35abd10610b98eaa06fd5742fc0bf5d4c0417d1db6aee6b3'),
    }
    if device.path == '/device-tree/arm-io/dart-adreno':
        # Generated by probes/adreno.py from dart-sio's property set; the
        # fingerprint below is of that generated node (tools/test-adreno-image.py).
        policies[device.path] = ('Adreno', DART_ADRENO_BOOT_V1, 16, ((0x710000000, 0x20000),),
                                 ADRENO_DART_FINGERPRINT_WIDE if ADRENO_DART_WIDE else ADRENO_DART_FINGERPRINT)
    if device.path not in policies:
        return 44
    label,policy,streams,windows,expected=policies[device.path]
    # Includes the complete property set, so added bypass, no-sleep, reset,
    # APF, firmware mappings or performance policies cannot silently opt in.
    digest=hashlib.sha256()
    for key in sorted(dt.nodes[device.path]):
        if key == 'dart-id':
            continue
        if policy==DART_ANE_INIT_V1 and key=='allow-dram-apf-slices-0':
            continue  # Derived from chosen/dram-base and checked below.
        prop=dt.nodes[device.path][key]
        if prop.placeholder:
            raise ValueError(f'{label} DART boot policy has unresolved properties')
        value=dt.get(device.path,key)
        digest.update(key.encode()+b'\0'+struct.pack('<I',len(value))+value)
    if (digest.hexdigest()!=expected or device.sid_count!=streams or
            device.windows!=windows or
            (policy==DART_SEP_BOOT_V1 and device.device_id!=20) or
            (policy==DART_ANE_INIT_V1 and device.device_id!=0) or
            (policy==DART_ADRENO_BOOT_V1 and device.device_id!=31)):
        raise ValueError(f'{label} DART boot policy differs from the audited topology')
    if policy==DART_ANE_INIT_V1:
        # The immutable fingerprint includes the exact four APF slices. The
        # exception list is present only for slices above relocated DRAM;
        # bind its complete value to this tree's placement, not a fixture PA.
        dram=dt.nodes.get('/device-tree/chosen',{}).get('dram-base')
        indices=[]
        if dram is not None:
            if dram.placeholder or len(dram.value)!=8:
                raise ValueError('ANE DART requires resolved DRAM placement')
            base=struct.unpack('<Q',dram.value)[0]
            if not 0<base<1<<36:
                raise ValueError('ANE DART has invalid DRAM placement')
            raw=dt.get(device.path,'dapf-instance-0')
            indices=[i for i in range(len(raw)//52)
                     if struct.unpack_from('<Q',raw,i*52+8)[0]>=base]
        expected_allow=struct.pack(f'<{len(indices)}I',*indices) if indices else None
        allow=dt.nodes[device.path].get('allow-dram-apf-slices-0')
        if ((allow is not None and allow.placeholder) or
                dt.get(device.path,'allow-dram-apf-slices-0')!=expected_allow):
            raise ValueError('ANE DART APF exceptions differ from DRAM placement')
    return policy


