def mcc_ptd_models(dt, spec, windows):
    """Resolve the audited MCC protocol through the firmware's PTD directory.

    Register placement and PTD indices belong to the guest profile. A single
    descriptor joins the database and update aliases to one virtual state.
    """
    if dt.get(spec.node, 'compatible').rstrip(b'\0') != spec.compatible:
        raise ValueError('MCC PTD node does not match the audited register ABI')

    def u32(name):
        value = dt.get(spec.node, name)
        if len(value) != 4:
            raise ValueError(f'invalid MCC PTD property {name}')
        return struct.unpack('<I', value)[0]

    db_index, update_index = u32('pmp_ptd_db_reg_idx'), u32('pmp_ptd_update_reg_idx')
    if max(db_index, update_index) >= len(windows):
        raise ValueError('MCC PTD register index outside window list')
    (base, db_size), (update, update_size) = windows[db_index], windows[update_index]
    if db_size != 0x4000 or update_size != 0x4000 or update < base+db_size:
        raise ValueError('unsupported MCC PTD aperture geometry')
    data = dt.get(spec.pmp_node, 'ptd-range')
    if not data or len(data) % 32:
        raise ValueError('invalid PMP PTD directory')
    entries = {}
    for ident, first, count, flags, name in struct.iter_unpack('<IIII16s', data):
        if ident in entries:
            raise ValueError('duplicate PMP PTD range ID')
        entries[ident] = (first, count, flags, name.rstrip(b'\0'))
    ranges = []
    for prop, expected_name, extra in (
            ('ptd-range-drv2ctrl', b'MC-DRV-TO-CTRL', 2),
            ('ptd-range-ctrl2drv', b'MC-CTRL-TO-DRV', 1)):
        entry = entries.get(u32(prop))
        if (entry is None or entry[1:] != (spec.quota_words+extra, 0, expected_name)):
            raise ValueError('unsupported MCC PTD range contract')
        ranges.append(entry[0])
    models = (DeviceModel(spec.node, MCC_PTD_COHERENT_V1, base, update+update_size-base,
                          (update-base, *ranges, spec.quota_words, 0)),)
    device_model_words(models)
    return models


def pmp_active_models(dt, models):
    """Bind PMP physical-domain votes to the registered PMGR backends.

    Preserve the shared MCC data/update aperture and supported row mask.
    AVD/ISP/PRORES/VENC/MSR/JPG/GFX own power/vote transitions and state-derived ACKs; other
    covered domains remain active. PMP-STATUS describes successful virtual
    registry initialization. Virtual devices, additional voters and DVFS
    packets need separate contracts.
    """
    pmgr='/device-tree/arm-io/pmgr'
    pmp='/device-tree/arm-io/pmp/iop-pmp-nub'
    for path,name,digest in (
        (pmgr,'devices','695eaa2f3def5f2fe9e7e8a97306b2ba44ff2f246b97c4f80a8c46bd496aa384'),
        (pmgr,'reg','228f2f75c199e9c0cdb99d16d484c2dade36d02673f8826d062e195de2b446f3'),
        (pmgr,'ptd-ranges','badb95d4143a7953cf071ff545271711fd754331253e5d2b966a4f47459ac69e'),
        (pmp,'ptd-range','2114f1290101b1d573fcae3ac905ccc322f30ee1e125fa54511bd1e825bcc29a'),
        (pmp,'soc-device','d9332c697501717107223fcf3b7fb500ecf7b7bd64d73d1afed7084b0e1e1ba1')):
        prop=dt.nodes.get(path,{}).get(name)
        if (prop is None or prop.placeholder or
                hashlib.sha256(bytes(prop.value)).hexdigest()!=digest):
            raise ValueError(f'PMP active-domain {name} contract changed')
    for path,name,expected in (
        (pmgr,'pmp',struct.pack('<I',2)),
        (pmgr,'pmp-voter-agent-idx',struct.pack('<I',0)),
        (pmp,'ptd-driver-version',struct.pack('<I',1)),
        (pmp,'soc-device-ps-group',struct.pack('<Q',0x080fff80))):
        prop=dt.nodes.get(path,{}).get(name)
        if prop is None or prop.placeholder or prop.value!=expected:
            raise ValueError(f'PMP active-domain {name} topology changed')
    physical={row[3] for row in (dt.get(pmgr,'devices')[i:i+48]
              for i in range(0,len(dt.get(pmgr,'devices')),48)) if not row[0]&16 and row[3]}
    rows=tuple(struct.iter_unpack('<31I',dt.get(pmp,'soc-device')))
    mask=sum(1<<i for i,row in enumerate(rows) if row[0] in physical)
    if mask!=PMP_ACTIVE_MASK:
        raise ValueError('PMP active-domain row mapping differs from the backend')
    old=[i for i,m in enumerate(models) if m.kind==MCC_PTD_COHERENT_V1]
    if len(old)!=1 or models[old[0]].words()[1:]!=(0x3003c0000,0x14000,0x10000,0x1a8,0x1b8,8,0):
        raise ValueError('PMP active-domain shared PTD aperture changed')
    result=list(models)
    result[old[0]]=replace(result[old[0]],kind=PTD_PMP_ACTIVE_V1,
                           config=(0x10000,0x1a8,0x1b8,8,mask))
    device_model_words(result)
    return tuple(result)


def _gpio_routes_valid(model):
    routes = model.config[3:]
    if model.kind == GPIO_QUIET_V1:
        return not any(routes)
    if model.kind == GPIO_IDLE_INPUTS_V1:
        if any(word >> 54 for word in routes):
            return False
        routes = tuple((word >> (18*i)) & 0x3ffff for word in routes for i in range(3))
    elif model.kind == GPIO_IDLE_PADS_V2:
        if any(word>>44 for word in routes):return False
        raw=tuple((word>>(11*i))&0x7ff for word in routes for i in range(4))
        routes=tuple((v&0x1ff)|((v>>9)<<16) for v in raw)
    if model.kind not in (GPIO_UART_RX_IDLE_V1, GPIO_IDLE_INPUTS_V1, GPIO_IDLE_PADS_V2) or not routes[0]:
        return False
    pins = []
    for route in routes:
        if not route:
            continue
        pin, mux = route & 0xffff, route >> 16
        if not 1 <= pin <= model.config[0] or not 1 <= mux <= 3 or pin in pins:
            return False
        pins.append(pin)
    return True


def device_model_words(models, excluded=()):
    """Validate the whole registry before publishing a fixed-size ABI block."""
    if len(models) > MODEL_MAX:
        raise ValueError('too many virtual device models')
    used = list(excluded)
    if any(type(b) is not int or type(n) is not int or b < 0 or n < 0 or
           b+n >= 1 << 64 for b, n in used):
        raise ValueError('invalid excluded memory range')
    words = [len(models)]
    for model in models:
        values = model.words()
        if len(values) != MODEL_WORDS or any(type(v) is not int or not 0 <= v < 1 << 64 for v in values):
            raise ValueError('malformed virtual device descriptor')
        if model.kind == MCC_COHERENT_V1 and 1 <= model.config[0] <= 4:
            minimum = max((model.config[0]-1)*0x40000 + 0x2e008, 0x102804)
        elif model.kind == MCC_DCS_COHERENT_V1 and model.config[0] == 0:
            minimum = 0x4070
        elif model.kind == MCC_SOCNI_V1 and 1 <= model.config[0] <= 64:
            minimum = 0x4000 + model.config[0]*8
        elif model.kind == WATCHDOG_WD1_V1 and 0 < model.config[0] <= 0xffffffff:
            minimum = 0x20
        elif (model.kind == WATCHDOG_SMC_DISARM_V1 and model.span == 0x1000 and
              model.config[0] == 8):
            minimum = model.span
        elif (model.kind == AOP_TIMEBASE_V1 and model.span == 0x1000 and
              model.config[0] == 24000000):
            minimum = 0x1000
        elif (model.kind == PMGR_ACTIVE_BOOT_V1 and model.config[0] in (0,1) and
              model.span == (0x11000,0x9000)[model.config[0]] and
              model.config[1] in ((0,) if model.config[0] else (0,PMGR_CPU0_BOOT_V1)) and
              not any(model.config[2:])):
            minimum = model.span
        elif (model.kind == PMGR_AON_FUSES_V1 and model.span == 0x4000 and
              model.config[0] == 0):
            minimum = model.span
        elif (model.kind == PMGR_CPU_PERF_BOOT_V1 and model.span == 0x1000 and
              model.config[0] in (0,1)):
            minimum = model.span
        elif (model.kind == PMGR_DVMR_WEIGHTS_V1 and model.span == 0x1000 and
              model.config[0] in (0,1)):
            minimum = model.span
        elif (model.kind == PMGR_AON_COUNTER_CONFIG_V1 and model.span == 0x1000 and
              model.config[0] in (6,7)):
            minimum = model.span
        elif (model.kind == PMGR_SOC_PERF_RESTORE_V1 and 0<=model.config[0]<=5 and
              model.span == (0x2000 if model.config[0]==0 else 0x3000 if model.config[0]==1 else 0x1000)):
            minimum = model.span
        elif (model.kind == PMGR_ACC_PERF_RESTORE_V1 and model.config[0] in (0,1)
              and model.span == 0x2000):
            minimum = model.span
        elif (model.kind == PMGR_ACC_BOOT_POLICY_V1 and model.span == 0x1000 and
              model.config[0] in (0,1)):
            minimum = model.span
        elif (model.kind == PMGR_LLT_DISABLED_V1 and model.base == 0x300740000 and
              model.span == 0x1000 and model.config[0] == 0):
            minimum = model.span
        elif (model.kind == CORESIGHT_LOCK_V1 and model.span == 0x1000 and
              0 <= model.config[0] < 6 and model.base ==
              (0x210010000+model.config[0]*0x100000 if model.config[0]<4 else
               0x211010000+(model.config[0]-4)*0x100000)):
            minimum = model.span
        elif (model.kind == QSPI_BOOT_V1 and model.span == 0x5000 and model.config[0] == 0):
            minimum = model.span
        elif (model.kind == DWI_STARTUP_V1 and model.base == 0x300200000 and
              model.span == 0x4000 and model.config[0] == 0):
            minimum = model.span
        elif (model.kind == I2C_EMPTY_V1 and model.base == 0x385018000 and
              model.span == 0x4000 and model.config == (2,6,1110,0,0)):
            minimum = model.span
        elif (model.kind == SEP_ASC_MAILBOX_V1 and model.base == 0x282600000 and
              model.span == 0x9000 and model.config in ((8,0,0,0,0),(8,1,346,343,0),(8,1,346,343,1),(8,1,346,343,3),(8,1,346,343,7),(8,1,346,343,11),(8,1,346,343,15),(8,1,346,343,19),(8,1,346,343,27),(8,1,346,343,59))):
            minimum = model.span
        elif (model.kind in (ANS_ASC_V1, ANS_NVME_V1) and
              (model.base, model.span) == (ANS_NVME_WINDOW if model.kind == ANS_NVME_V1 else ANS_ASC_WINDOW) and
              0 < model.config[0] < (1 << 36)-ANS_DISK_OFFSET-ANS_DISK_MAX and not model.config[0] % 0x4000 and
              not model.config[4] and
              (model.config[1:4] == (1010, 1007, 0) if model.kind == ANS_ASC_V1 else
               model.config[2] == 1039 and
               ((model.config[3] == ANS_WINDOW_MODE and not model.config[0] % (1 << 20) and
                 model.config[1] >= 1 << 30 and not model.config[1] % (1 << 20)) or
                (model.config[3] == 0 and 0 < model.config[1] <= ANS_DISK_MAX and
                 not model.config[1] % 0x1000)))):
            minimum = model.span
        elif (model.kind == PMGR_CPU_CLUSTER_ACTIVE_V1 and model.span == 0x1000 and
              model.config[0] in (0,PMGR_AVE_CLUSTER_V1)):
            minimum = model.span
        elif (model.kind in (PMGR_AP_WAKE_MASK_V1, PTD_IRQ_CONFIG_V1,
                            PMGR_AVE_TVM_IDLE_V1, PMGR_SOC_GATE_POLICY_V1,
                            PMGR_AXI2AF_POLICY_V1, PMC_ENABLE_POLICY_V1,
                            PMC_RMBS_REQUEST_V1, PMGR_ENERGY_RESTORE_V1) and model.span == 0x1000 and
              model.config[0] == 0):
            minimum = model.span
        elif (model.kind == PMGR_SOC_DPE_POLICY_V1 and model.span == 0x3000 and
              model.config[0] == 0):
            minimum = model.span
        elif (model.kind == PMC_DVMR_CONFIG_V1 and model.span == 0x6000 and
              model.config[0] == 0):
            minimum = model.span
        elif (model.kind == DART_T8110_V1 and model.span in (0xc000,0x20000) and
              1<=model.config[0]<=256 and
              (model.config[1]==44 or (model.config[1]==DART_SIO_BOOT_V1 and
               model.config[0]==16 and model.span==0x20000 and model.config[4] and
               not model.config[4]&(model.config[4]-1)) or
               (model.config[1]==DART_SEP_BOOT_V1 and model.base==0x280b80000 and
                model.span==0x20000 and model.config[0]==3 and model.config[2]==353 and
                model.config[4]==1<<20) or
               (model.config[1]==DART_ADRENO_BOOT_V1 and model.span==0x20000 and
                model.config[0]==16 and model.config[4]==1<<31) or
               (model.config[1]==DART_ANE_INIT_V1 and
                (model.base,model.span) in ((0x401800000,0xc000),
                    (0x401820000,0x20000),(0x401840000,0x20000)) and
                model.config[0]==16 and model.config[2]==656 and model.config[4]==1)) and
              model.config[2]<4096 and model.config[3]==36 and model.config[4]<1<<32):
            minimum = model.span
        elif (model.kind in (SPMI_GEN3_EMPTY_V1,SPMI_PMU_RTC_V1) and model.config[0] >= 0x8000 and
              model.config[0] % 0x4000 == 0 and model.span == model.config[0]+0x4000 and
              0x4000 <= model.config[1] <= model.config[0]-0x4000 and
              model.config[1] % 0x4000 == 0 and model.config[2] < 4096 and
              ((model.kind==SPMI_GEN3_EMPTY_V1 and model.config[3:]==(256,256)) or
               (model.kind==SPMI_PMU_RTC_V1 and model.base==0x308700000 and
                model.config[:3]==(0x14000,0x4000,487) and
                0<=model.config[3]<=PMU_RTC_LIMIT_US and model.config[4]==PMU_RTC_CONTRACT))):
            minimum = model.config[0]+0x4000
        elif (model.kind in (GPIO_QUIET_V1, GPIO_UART_RX_IDLE_V1, GPIO_IDLE_INPUTS_V1, GPIO_IDLE_PADS_V2) and
              1 <= model.config[0] <= 256 and
              1 <= model.config[1] <= 7 and 0 < model.config[2] < 1 << model.config[1] and
              _gpio_routes_valid(model)):
            minimum = 0x800 + model.config[1]*0x40
        elif (model.kind == DOCK_ABSENT_V1 and model.span == 0x1000 and
              model.config[0] % 4 == 0 and model.config[0] <= 0xffc and
              0 < model.config[1] <= 0xffffffff and
              not model.config[1] & (model.config[1]-1) and not any(model.config[2:])):
            minimum = 0x1000
        elif (model.kind == DOCK_FIFO_V1 and model.span == 0x35000 and
              model.config[:2] == (0x14000, 0x28000) and model.config[2] < 4096 and
              model.config[3:] == (2048, 0)):
            minimum = 0x35000
        elif model.kind == SOCNI_ERRORS_V1 and model.span == 0x4000 and model.config[0] < 6:
            minimum = 0x4000
        elif (model.kind == PLATFORM_ERROR_POLICY_V1 and not any(model.config[2:]) and
              ((model.span == 0x1000 and model.config[:2] == (0x104,1)) or
               (model.span == 0x20000 and model.config[:2] == (0x4084,0)))):
            minimum = model.span
        elif (model.kind == AES_IDLE_V1 and model.span == 0x4000 and
              model.config == (5,0,0,0,0)):
            minimum = model.span
        elif (model.kind == AES_SOFTWARE_V1 and model.span == 0x4000 and
              model.config == (5,42,1107,21,1)):
            minimum = model.span
        elif (model.kind == AES_NO_KEYS_V1 and
              len(set(model.config[:4])) == 4 and
              all(v % 4 == 0 for v in model.config[:4]) and
              (not model.config[4] or (model.config[4] % 4 == 0 and
                                       model.config[4] not in model.config[:4]))):
            # config[4]: zero, or PMGR's BPR word (docs/PMGR-BPR-20261017.md).
            minimum = max(model.config)+4
        elif (model.kind == PTD_PMP_ACTIVE_V1 and model.span == 0x14000 and
              model.config == (0x10000,0x1a8,0x1b8,8,PMP_ACTIVE_MASK)):
            minimum = model.span
        elif (model.kind == MCC_PTD_COHERENT_V1 and
              model.config[0] >= 0x4000 and model.config[0] % 0x1000 == 0 and
              model.span == model.config[0]+0x4000 and 1 <= model.config[3] <= 8 and
              model.config[1] <= 1024-model.config[3]-2 and
              model.config[2] <= 1024-model.config[3]-1 and not model.config[4] and
              (model.config[1]+model.config[3]+2 <= model.config[2] or
               model.config[2]+model.config[3]+1 <= model.config[1])):
            minimum = model.config[0]+0x4000
        elif (model.kind == AIC3_FLAT_V1 and 0 < model.config[0] <= 4096 and
              model.config[0] % 32 == 0 and model.config[1] == 4096 and
              model.config[2] >= 0x14a00 and model.config[2] % 4 == 0 and
              model.config[3] == 0xa and model.config[4] == 0):
            minimum = model.config[2] + 4
        else:
            raise ValueError('unsupported virtual device configuration')
        if model.kind not in (AIC3_FLAT_V1, MCC_PTD_COHERENT_V1, PTD_PMP_ACTIVE_V1,
                              GPIO_QUIET_V1, AES_NO_KEYS_V1, SPMI_GEN3_EMPTY_V1, SPMI_PMU_RTC_V1,
                              DOCK_ABSENT_V1, GPIO_UART_RX_IDLE_V1,
                              GPIO_IDLE_INPUTS_V1, GPIO_IDLE_PADS_V2, DOCK_FIFO_V1,
                              PLATFORM_ERROR_POLICY_V1, DART_T8110_V1, PMGR_ACTIVE_BOOT_V1,
                              I2C_EMPTY_V1, AES_SOFTWARE_V1, SEP_ASC_MAILBOX_V1,
                              ANS_ASC_V1, ANS_NVME_V1) and any(model.config[1:]):
            raise ValueError('unsupported virtual device configuration')
        if (not model.span or (model.base | model.span) & 0xfff or
                model.base + model.span > 1 << 36 or
                model.span < minimum):
            raise ValueError('invalid virtual device window')
        if any(n and model.base < b+n and b < model.base+model.span for b, n in used):
            raise ValueError('virtual device window overlaps another device or owned memory')
        used.append((model.base, model.span))
        words.extend(values)
    if any(m.kind==PTD_PMP_ACTIVE_V1 for m in models):
        for group,base,span in ((0,0x300700000,0x11000),(1,0x308280000,0x9000)):
            if not any(m.kind==PMGR_ACTIVE_BOOT_V1 and (m.base,m.span,m.config[0])==(base,span,group)
                       for m in models):
                raise ValueError('PMP votes require both registered active PMGR backends')
    if any(m.kind==PMGR_ACTIVE_BOOT_V1 and m.config[1]==PMGR_CPU0_BOOT_V1 for m in models):
        required={(PMGR_ACTIVE_BOOT_V1,0x300700000,0x11000,0,1,0,0,0),
                  (PMGR_ACTIVE_BOOT_V1,0x308280000,0x9000,1,0,0,0,0)}
        if not required<={m.words() for m in models} or not any(
                m.kind==PMGR_CPU_CLUSTER_ACTIVE_V1 and m.base==0x300780000 and
                m.span==0x1000 for m in models):
            raise ValueError('CPU boot power policy requires both PMGR banks and the active cluster controls')
    if any(m.kind==PMGR_AVE_TVM_IDLE_V1 or
           (m.kind==PMGR_CPU_CLUSTER_ACTIVE_V1 and m.config[0]) for m in models):
        required={(PMGR_CPU_CLUSTER_ACTIVE_V1,0x300780000,0x1000,1,0,0,0,0),
                  (PMGR_AVE_TVM_IDLE_V1,0x300760000,0x1000,0,0,0,0,0)}
        if not required<={m.words() for m in models}:
            raise ValueError('AVE cluster policy requires its exact cluster and TVM owners')
    ans = [m for m in models if m.kind in (ANS_ASC_V1, ANS_NVME_V1)]
    if ans:
        # One pair sharing one reservation that misses every owned range
        # (compat/device.c device_models_valid makes the same check).
        if (sorted(m.kind for m in ans) != [ANS_ASC_V1, ANS_NVME_V1] or
                len({m.config[0] for m in ans}) != 1):
            raise ValueError('virtual ANS2 needs exactly one ASC and NVMe pair on one reservation')
        nvme = next(m for m in ans if m.kind == ANS_NVME_V1)
        base = ans[0].config[0]
        span = ANS_WINDOW_BYTES if nvme.config[3] == ANS_WINDOW_MODE else ANS_DISK_OFFSET + nvme.config[1]
        if any(n and base < b+n and b < base+span for b, n in list(excluded)+used[len(excluded):]):
            raise ValueError('virtual ANS2 reservation overlaps owned memory or a device')
    words.extend([0] * ((MODEL_MAX-len(models))*MODEL_WORDS))
    return words
