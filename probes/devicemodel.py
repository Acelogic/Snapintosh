ANS_WINDOW_MODE = 1               # compat/ans.h: NVMe model config[3]
ANS_WINDOW_BYTES = 0x500000       # state, firmware, GPT, SSD params/DMA and1MiB staging


def ans_reservation_span(disk_bytes, window=False):
    """Bytes the monitor needs for one virtual ANS2: state, reserved page, disk (or the window's)."""
    if window:
        if type(disk_bytes) is not int or disk_bytes < 1 << 30 or disk_bytes % (1 << 20):
            raise ValueError('invalid virtual ANS2 window size')
        return ANS_WINDOW_BYTES
    if type(disk_bytes) is not int or not 0 < disk_bytes <= ANS_DISK_MAX or disk_bytes % 0x1000:
        raise ValueError('invalid virtual ANS2 disk size')
    return (ANS_DISK_OFFSET + disk_bytes + 0xffff) & ~0xffff


# The firmware state iBoot publishes on the IOP nub once it has booted ANS2
# and left it quiesced. The 26A428 template (DeviceTree.j700ap) has none of it;
# the live Mac17,5 ADT does (uuid, segment-names "__TEXT;__DATA",
# segment-ranges, pre-loaded 1, running 1; docs/ANS2-FIRMWARE-STATE-20260925.md).
# Without it RTBuddy::_initConfigEDT (0xfffffe000b327c98) leaves pre-loaded,
# running and no-firmware-service clear, _attemptFirmwareLoad
# (0xfffffe000b320c70) waits for an RTBuddyFirmwareService with Role ANS2 that
# no 26A428 kext provides, and _setPowerStateGuardEntryGated
# (0xfffffe000b322ea0) refuses every power change without firmware: the IOP is
# never woken. With it, _handlePreloadFirmware -> loadFirmware -> setPowerState(1).
ANS_NUB = '/iop-ans-nub'
# segment-ranges flags word (RTBuddy::getSegmentMap 0xfffffe000b328a88):
# bit0 read-only, bit2 needs backup, bit3 AP-kernel memory, bit4 restricted
# (RTBuddyCoredumpMap::initWithSegments 0xfffffe000b313a84 never maps it).
ANS_SEGMENT_READ_ONLY = 0x1
ANS_SEGMENT_RESTRICTED = 0x10
ANS_FIRMWARE_PROPERTIES = ('segment-names', 'segment-ranges', 'pre-loaded', 'running')


def ans_firmware_state(reservation):
    """The nub properties that describe the virtual IOP as iBoot-booted and quiesced.

    One segment, "__TEXT", at IOP address 0: the monitor's reserved zero page
    (reservation + ANS_FW_OFFSET), read-only and restricted, so XNU records it
    in a physical memory descriptor and never maps it. No firmware image is
    presented and nothing the guest reaches is backed by it; an access would
    stop the run at stage 2 with this address. Record layout (32 bytes):
    physical address, IOP address, physical address, u32 size, u32 flags."""
    if type(reservation) is not int or reservation<=0 or reservation%0x10000:
        raise ValueError('invalid virtual ANS2 reservation')
    pa=reservation+ANS_FW_OFFSET
    return (('segment-names', b'__TEXT\0'),
            ('segment-ranges', struct.pack('<QQQII', pa, 0, pa, ANS_FW_BYTES,
                                           ANS_SEGMENT_READ_ONLY|ANS_SEGMENT_RESTRICTED)),
            ('pre-loaded', struct.pack('<I', 1)),
            ('running', struct.pack('<I', 1)))


def _ans_stock_subtree(dt, node):
    """The ANS2 subtree serialized without the published firmware state."""
    props=dt.nodes.get(node+ANS_NUB)
    if props is None:
        raise ValueError('ANS2 IOP nub missing')
    saved=dict(props)
    try:
        for name in ANS_FIRMWARE_PROPERTIES:
            props.pop(name, None)
        return dt.serialize(node)
    finally:
        props.clear()
        props.update(saved)


def populate_ans_firmware(dt, spec, reservation):
    """Publish the virtual ANS2's firmware state on the stock, pinned nub.

    Only these four properties are added; the template must carry none of
    them and must still be the audited subtree (quiesced, power-managed,
    no user power management, no firmware-service opt-out, empty region)."""
    nub=spec.node+ANS_NUB
    props=dt.nodes.get(nub)
    if spec.node!='/device-tree/arm-io/ans' or props is None:
        raise ValueError('ANS2 node identity changed')
    if any(name in props for name in ANS_FIRMWARE_PROPERTIES):
        raise ValueError('ANS2 IOP nub already carries firmware state')
    if hashlib.sha256(dt.serialize(spec.node)).hexdigest()!=spec.sha256:
        raise ValueError(f'ANS2 firmware subtree changed: {spec.node}')
    if (dt.get(nub,'compatible')!=b'iop-nub,rtbuddy-v2\0' or dt.get(nub,'quiesced')!=b'' or
            dt.get(nub,'power-managed')!=struct.pack('<I',1) or
            any(dt.get(nub,k) is not None for k in ('user-power-managed','no-firmware-service',
                                                     'dont-power-on','reconfig-firmware','uuid')) or
            dt.get(nub,'region-base')!=bytes(8) or dt.get(nub,'region-size')!=bytes(8)):
        raise ValueError('ANS2 IOP nub contract changed')
    for name,value in ans_firmware_state(reservation):
        dt.add(nub, name, value)


def ans_models(dt, spec, windows, sart_windows, reservation):
    """Bind the stock ANS2 nodes to the monitor's virtual ANS2 (compat/ans.c).

    Apple's own AppleASCWrapV6/RTBuddy/IONVMeFamily drivers match these nodes
    unchanged; only the register windows the 26A428 drivers touch outside the
    SPTM are modeled (the ASC mailbox pages and the NVMe BAR, which holds the
    NVMMU and the coastguard SART window). Everything else stays absent at
    stage 2, so an unexpected access stops the run with its IPA. The nub must
    carry exactly the firmware state populate_ans_firmware publishes for this
    reservation, after the pinned template properties.
    """
    if (spec.node!='/device-tree/arm-io/ans' or spec.sart_node!='/device-tree/arm-io/sart-ans' or
            spec.node not in dt.nodes or spec.sart_node not in dt.nodes):
        raise ValueError('ANS2 node identity changed')
    if tuple(windows)!=ANS_REG_WINDOWS or tuple(sart_windows)!=ANS_SART_WINDOWS:
        raise ValueError('ANS2 register topology changed')
    for node,digest in ((spec.node,spec.sha256),(spec.sart_node,spec.sart_sha256)):
        nodes=[n for n in dt.nodes if n==node or n.startswith(node+'/')]
        if any(p.placeholder for n in nodes for p in dt.nodes[n].values()):
            raise ValueError('ANS2 has unresolved metadata')
        serialized=_ans_stock_subtree(dt, node) if node==spec.node else dt.serialize(node)
        if hashlib.sha256(serialized).hexdigest()!=digest:
            raise ValueError(f'ANS2 firmware subtree changed: {node}')
    nub=dict(dt.nodes[spec.node+ANS_NUB])
    if (list(nub)[-len(ANS_FIRMWARE_PROPERTIES):]!=list(ANS_FIRMWARE_PROPERTIES) or
            tuple((k,bytes(nub[k].value)) for k in ANS_FIRMWARE_PROPERTIES)!=ans_firmware_state(reservation)):
        raise ValueError('ANS2 IOP firmware state differs from the virtual ANS2')
    if (dt.get(spec.node,'compatible')!=b'iop,ascwrap-v6\0' or dt.get(spec.node,'role')!=b'ANS2\0' or
            dt.get(spec.node,'interrupts')!=struct.pack('<5I',1008,1007,1010,1009,1039) or
            dt.get(spec.node,'nvme-interrupt-idx')!=struct.pack('<I',4) or
            dt.get(spec.node,'nvme-queue-entries')!=struct.pack('<I',64) or
            dt.get(spec.node,'nvme-linear-sq')!=b'' or
            dt.get(spec.node,'iommu-parent')!=dt.get(spec.sart_node,'AAPL,phandle') or
            dt.get(spec.sart_node,'compatible')!=b'sart,coastguard\0' or
            dt.get(spec.sart_node,'sart-version')!=struct.pack('<I',3)):
        raise ValueError('ANS2 driver contract changed')
    pinned = (len(spec.window_guid) == 36 and len(spec.window_gpt) == 3 if spec.window else
              type(spec.disk_sha256) is str and len(spec.disk_sha256) == 64)   # window: the partition GUID pins it
    if (not pinned or type(reservation) is not int or reservation<=0 or reservation%0x10000):
        raise ValueError('invalid virtual ANS2 reservation')
    ans_reservation_span(spec.disk_bytes, spec.window)
    if spec.window and reservation % (1 << 20):
        raise ValueError('the window reservation must be 1 MiB aligned (the SSD DMA window)')
    models=(DeviceModel(spec.node,ANS_ASC_V1,*ANS_ASC_WINDOW,(reservation,1010,1007,0,0)),
            DeviceModel(spec.node,ANS_NVME_V1,*ANS_NVME_WINDOW,
                        (reservation,spec.disk_bytes,1039,ANS_WINDOW_MODE if spec.window else 0,0)))
    device_model_words(models)
    return models


def i2c_empty_models(dt, spec, windows):
    """An exact I2C2 frontend with no slave endpoints, hence address NACKs."""
    if (spec.node != '/device-tree/arm-io/i2c2' or
            tuple(windows) != ((0x385018000, 0x4000),) or
            spec.node not in dt.nodes):
        raise ValueError('I2C bus differs from the audited topology')
    nodes=[n for n in dt.nodes if n==spec.node or n.startswith(spec.node+'/')]
    if any(p.placeholder for n in nodes for p in dt.nodes[n].values()):
        raise ValueError('I2C bus contains unresolved metadata')
    if hashlib.sha256(dt.serialize(spec.node)).hexdigest()!=spec.sha256:
        raise ValueError('I2C bus firmware changed')
    expected={
        'clock-gates': struct.pack('<I',69),
        'interrupts': struct.pack('<I',1110),
        'interrupt-parent': struct.pack('<I',69),
    }
    if any(dt.get(spec.node,k)!=v for k,v in expected.items()):
        raise ValueError('I2C clock or interrupt contract changed')
    prop=dt.nodes.get('/device-tree/arm-io/pmgr',{}).get('devices')
    row=bytes.fromhex('00000000360000000000000000000000d802000000000000'
                      '000045000000000049324332000000000000000000000000')
    if prop is None or prop.placeholder or prop.value[3264:3312]!=row:
        raise ValueError('I2C2 PMGR gate changed')
    # Revision 6 describes our implemented master enable/control frontend,
    # not a sampled Qualcomm or physical Apple controller identity.
    model=DeviceModel(spec.node,I2C_EMPTY_V1,windows[0][0],0x4000,(2,6,1110,0,0))
    device_model_words((model,))
    return (model,)


