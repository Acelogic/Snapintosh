def dart_models(dt, devices):
    """Bind DART register instances; APF/SMMU windows keep separate contracts.

    Instance records are 16-byte type/index/name/variant tuples. Their order
    is the reg-array order; index names the logical instance, not a reg slot.
    The two alternative JPEG nodes share one physical DART. Admit that one
    audited alias explicitly, with capacity covering either profile.
    """
    models=[]
    by_base={}
    jpeg={'/device-tree/arm-io/dart-jpeg-h17a','/device-tree/arm-io/dart-jpeg0-h17p'}
    for device in devices:
        raw=dt.get(device.path,'instance') or b''
        irq=dt.get(device.path,'interrupts') or b''
        if (device.compatible!=b'dart,t8110' or device.page_size!=0x4000 or
                not raw or len(raw)!=16*len(device.windows) or len(irq)!=4 or
                dt.nodes[device.path]['instance'].placeholder or
                dt.nodes[device.path]['interrupts'].placeholder):
            raise ValueError(f'{device.path}: unaudited DART instance geometry')
        if not 0<=device.device_id<32:
            raise ValueError('DART model initialization ID exceeds the admitted bitmap')
        boot_policy=_dart_boot_policy(dt,device)
        # The pinned INIT handler walks the DART records, excluding ANE's
        # DAPF record. Admit that exact mixed topology for capability capture
        # only; APF setup, POWERUP and frame ownership remain separate.
        pure=all(raw[i:i+4]==b'TRAD' for i in range(0,len(raw),16))
        init_ids=(1<<device.device_id) if pure or boot_policy==DART_ANE_INIT_V1 else 0
        for n,(base,span) in enumerate(device.windows):
            kind=raw[16*n:16*n+4]
            if kind in (b'UMMS',b'FPAD'):continue
            if kind!=b'TRAD':raise ValueError(f'{device.path}: unknown IOMMU instance type')
            model=DeviceModel(device.path,DART_T8110_V1,base,span,
                              (device.sid_count,boot_policy,struct.unpack('<I',irq)[0],36,init_ids))
            if base in by_base:
                old=models[by_base[base]]
                if ({old.node,device.path}!=jpeg or span!=old.span or
                        model.config[1:4]!=old.config[1:4]):
                    raise ValueError('unrecognized DART register alias')
                models[by_base[base]]=replace(old,config=(max(old.config[0],model.config[0]),
                    *old.config[1:4],old.config[4]|model.config[4]))
            else:
                by_base[base]=len(models)
                models.append(model)
    device_model_words(models)
    return tuple(models)


