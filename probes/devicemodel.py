def sep_asc_models(dt, spec, windows):
    """Exact SEP ASC transport binding; firmware services are separate."""
    if type(spec.reply_transport) is not bool:
        raise ValueError('SEP ASC transport selection must be explicit')
    if type(spec.rom_status) is not bool or (spec.rom_status and not spec.reply_transport):
        raise ValueError('SEP ROM status producer requires explicit reply transport')
    if type(spec.service_bootstrap) is not bool or (spec.service_bootstrap and not spec.rom_status):
        raise ValueError('SEP service bootstrap requires explicit ROM frontend')
    if type(spec.pnon_recovery) is not bool or (spec.pnon_recovery and not spec.service_bootstrap):
        raise ValueError('SEP ordinary-recovery pnon requires explicit service bootstrap')
    if type(spec.xars_refusal) is not bool or (spec.xars_refusal and not spec.service_bootstrap):
        raise ValueError('SEP xars refusal service requires explicit service bootstrap')
    if type(spec.pnon_refusal) is not bool or (spec.pnon_refusal and not spec.service_bootstrap):
        raise ValueError('SEP pnon refusal service requires explicit service bootstrap')
    if type(spec.sks_startup) is not bool or (spec.sks_startup and not (
            spec.service_bootstrap and spec.xars_refusal and spec.pnon_refusal)):
        raise ValueError('SEP SKS startup requires installed pnon/xars services')
    if spec.pnon_recovery and spec.pnon_refusal:
        raise ValueError('SEP pnon recovery and refusal modes are mutually exclusive')
    if (spec.node!='/device-tree/arm-io/sep' or spec.node not in dt.nodes or
            tuple(windows)!=((0x282600000,0x88000),(0x282050000,0x60000))):
        raise ValueError('SEP ASC register topology changed')
    nodes=[n for n in dt.nodes if n==spec.node or n.startswith(spec.node+'/')]
    if any(p.placeholder for n in nodes for p in dt.nodes[n].values()):
        raise ValueError('SEP ASC has unresolved metadata')
    if hashlib.sha256(dt.serialize(spec.node)).hexdigest()!=spec.sha256:
        raise ValueError('SEP ASC firmware subtree changed')
    if (dt.get(spec.node,'compatible')!=b'iop-sep,ascwrap-v6\0' or
            dt.get(spec.node,'interrupts')!=struct.pack('<4I',344,343,346,345) or
            dt.get(spec.node,'clock-gates')!=b'' or dt.get(spec.node,'power-gates')!=b''):
        raise ValueError('SEP ASC frontend policy changed')
    # Preserve every established model index. The frontend covers the
    # mailbox pages only and never makes the firmware/security windows RAM.
    config=(8,1,346,343,int(spec.rom_status)|int(spec.service_bootstrap)<<1|int(spec.pnon_recovery)<<2|int(spec.xars_refusal)<<3|int(spec.pnon_refusal)<<4|int(spec.sks_startup)<<5) if spec.reply_transport else (8,0,0,0,0)
    model=DeviceModel(spec.node,SEP_ASC_MAILBOX_V1,windows[0][0],0x9000,config)
    device_model_words((model,))
    return (model,)


